#!/usr/bin/env python3
"""Build data/rs_gear_defs.json — Rocksmith 2014 gear knob definitions.

Reads manifests/gears/*.json out of Rocksmith 2014's gears.psarc.  Each gear
manifest defines every knob the game exposes: its RTPC key (the exact key a
tone's KnobValues uses), display name, unit (number, %, db, ms, hz, khz,
enum), default, min, max, step, and enum labels.  Rocksmith+ tones use the
same gear keys for everything except a handful of Rocksmith+-only models.

The PSARC table of contents is AES-256-CFB encrypted with the key the
Rocksmith modding community has documented for years (rocksmith-custom-
song-toolkit, 0x0L/rocksmith, etc.); the manifests themselves are plain zlib.
Needs the `cryptography` package.

Usage:
    python tools/extract_rs_gear.py [--psarc PATH] [-o data/rs_gear_defs.json]
"""
import argparse
import json
import re
import struct
import warnings
import zlib
from pathlib import Path

DEFAULT_PSARC = Path("C:/Program Files (x86)/Steam/steamapps/common/Rocksmith2014/gears.psarc")
ARC_KEY = bytes.fromhex("C53DB23870A1A2F71CAE64061FDD0E1157309DC85204D4C5BFDF25090DF2572C")
ARC_IV = bytes.fromhex("E915AA018FEF71FC508132E4BB4CEB42")


class Psarc:
    def __init__(self, path: Path):
        self.f = open(path, "rb")
        h = self.f.read(32)
        if h[:4] != b"PSAR":
            raise ValueError(f"{path} is not a PSARC")
        self.toc_len, self.entry_size, n, self.block_size, flags = struct.unpack(">IIIII", h[12:32])
        toc = self.f.read(self.toc_len - 32)
        if flags == 4:
            from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                dec = Cipher(algorithms.AES(ARC_KEY), modes.CFB(ARC_IV)).decryptor()
            toc = (dec.update(toc + b"\0" * ((-len(toc)) % 16)) + dec.finalize())[:len(toc)]
        self.entries = []
        for i in range(n):
            o = i * self.entry_size
            self.entries.append((toc[o:o + 16], struct.unpack(">I", toc[o + 16:o + 20])[0],
                                 int.from_bytes(toc[o + 20:o + 25], "big"),
                                 int.from_bytes(toc[o + 25:o + 30], "big")))
        if self.entries[0][0] != b"\0" * 16:
            raise ValueError("PSARC table of contents did not decrypt (wrong key?)")
        zb = {65536: 2, 16777216: 3}.get(self.block_size, 4)
        zraw = toc[n * self.entry_size:]
        self.zsizes = [int.from_bytes(zraw[i:i + zb], "big") for i in range(0, len(zraw) - zb + 1, zb)]
        self.names = [""] + self.read(0).decode("utf-8", "replace").split("\n")

    def read(self, idx: int) -> bytes:
        _, z, length, off = self.entries[idx]
        self.f.seek(off)
        out = bytearray()
        while len(out) < length:
            zs = self.zsizes[z] or self.block_size
            chunk = self.f.read(zs)
            try:
                out += zlib.decompress(chunk)
            except zlib.error:
                out += chunk          # stored block
            z += 1
        return bytes(out[:length])


def knob_def(k: dict):
    rtpc = k.get("RTPC") or k.get("Key")
    if not rtpc or rtpc == "0":
        return None
    d = {"key": rtpc, "name": k.get("Name", ""), "unit": (k.get("UnitType") or "number").lower()}
    for src, dst in (("MinValue", "min"), ("MaxValue", "max"), ("DefaultValue", "default"),
                     ("ValueStep", "step")):
        if isinstance(k.get(src), (int, float)):
            d[dst] = k[src]
    if k.get("EnumValues"):
        d["enum"] = {str(lbl): float(v) for lbl, v in k["EnumValues"].items()}
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--psarc", type=Path, default=DEFAULT_PSARC)
    ap.add_argument("-o", "--output", type=Path,
                    default=Path(__file__).resolve().parent.parent / "data" / "rs_gear_defs.json")
    args = ap.parse_args()

    p = Psarc(args.psarc)
    gear = {}
    for i, name in enumerate(p.names):
        if not (name.startswith("manifests/gears/") and name.endswith(".json")):
            continue
        text = p.read(i).decode("utf-8", "replace")
        data = json.loads(re.sub(r",\s*([}\]])", r"\1", text))
        for e in data.get("Entries", {}).values():
            a = e.get("Attributes", {})
            if not a.get("Key"):
                continue
            knobs = [kd for kd in (knob_def(k) for k in a.get("Knobs", [])) if kd]
            gear[a["Key"]] = {"type": a.get("Type", ""), "name": a.get("Name", ""),
                              "category": a.get("Category", ""), "knobs": knobs}
    out = {"_source": {"psarc": str(args.psarc),
                       "note": "generated by tools/extract_rs_gear.py — do not hand-edit"},
           "gear": dict(sorted(gear.items()))}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(out, indent=1), encoding="utf-8")
    print(f"{len(gear)} gear definitions -> {args.output}")


if __name__ == "__main__":
    main()
